"""Originality as part of Product Truth: the IP firewall's publishable half.

Master v1.0, v0.23 sections 78-79 (F-783, F-785, F-791, F-794, F-795, F-798), read through the
Final Build supersession S1: **private, complete reverse-engineering of a purchased pattern is
allowed** (F-789, F-797) -- the teardown laboratory is encouraged to understand a competitor's
garment architecture as deeply as it can. What is forbidden is *publishing* their protected
text or images, or a light derivative of their design. This module is the boundary on the
publishing side, and every check in it is deterministic: an LLM may be asked for an opinion
about similarity, and the answer here wins even if every model disagrees.

Five things live here, each the runtime form of one requirement:

**1. Design provenance is required, not optional (F-783, F-798).** Every Brambleloop-authored
CIR must carry a complete `cir.model.Provenance`: the concept it realises, a digest of the
brief it was built from, the Brambleloop-owned primitives it used (motif library, grading
engine, shaping rules), and the benchmarks it consulted. `provenance_findings` refuses a
release without one. Until 2026-09-28 the record was stamped only on graded garments, so the
rest of the catalogue could be certified with nothing saying where its design came from --
which is the one fact a copyright question asks first.

**2. A competitor-informed design carries a design-difference ledger (F-794), and the ledger
must record a meaningful redesign (F-791).** When provenance lists benchmarks consulted, a
ledger entry per benchmark states what was learned, what Brambleloop changed, why each change
is better and which aspects were designed independently. `redesign_verdict` then refuses a
ledger whose changes are only the superficial ones F-791 names -- colour, yarn, wording, size
labels, button count, small dimensions, a few rows. A ledger is a claim; the classifier below
reads the claim's own words so an honest-looking label ("construction") on a superficial
change ("added two rows") does not pass.

**3. Similarity review before sale (F-795)** compares a candidate against every purchased
benchmark this company holds a fingerprint of -- both commercial benchmarks, the side-to-side
textured cardigan (benchmark 1) and the Mini Star Stitch Cardigan (benchmark 2) -- on four
dimensions: wording n-grams, unusual numeric sequences, distinctive feature combinations and
construction sequence. A dimension with nothing to compare (no benchmark text was ever
fingerprinted) is UNMEASURED, never "no overlap". Material overlap is escalated for redesign
rather than hidden: it is an ERROR finding naming the benchmark and the dimension.

**4. A benchmark or seller image is never a generation reference (F-785).**
`refuse_benchmark_reference` is called by the image gateway's request builder for every
reference image, before a request exists. Competitor photography is for private evaluation.

**5. Fingerprints, never text.** The only representation of a benchmark's wording anywhere in
this system is a set of salted, truncated hashes of its word 6-grams. They can say "these two
documents share 40% of their phrasing" and cannot be turned back into a sentence, which keeps
the rule of `teardown/library.py` -- no table holds a competitor's instructions -- intact.
"""
