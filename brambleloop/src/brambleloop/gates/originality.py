def record_fingerprint(db, ref: str, *, title: str = "", text: str | None = None,
                       features=(), construction=(), size_sequences=None,
                       piece_numbers=None, source: str = "teardown") -> dict:
    """Store a benchmark's fingerprint. `text` is hashed here and never stored."""
    from datetime import datetime, timezone

    from sqlalchemy import select

    from ..core.models import BenchmarkFingerprintRecord

    hashed = sorted(shingles(text)) if text else None
    with db.session() as s:
        row = s.scalar(select(BenchmarkFingerprintRecord).where(
            BenchmarkFingerprintRecord.benchmark_ref == ref))
        if row is None:
            row = BenchmarkFingerprintRecord(benchmark_ref=ref)
            s.add(row)
        row.title = title or row.title or ref
        if hashed is not None:
            row.wording_shingles = hashed
        if features:
            row.features = sorted(features)
        if construction:
            row.construction = list(construction)
        if size_sequences:
            row.size_sequences = {k: list(v) for k, v in size_sequences.items()}
        if piece_numbers:
            row.piece_numbers = {k: list(v) for k, v in piece_numbers.items()}
        row.source = source
        row.updated_at = datetime.now(timezone.utc)
        return {"ref": ref, "wording_shingles": len(row.wording_shingles or [])}


