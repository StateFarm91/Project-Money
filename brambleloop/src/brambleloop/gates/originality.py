SHINGLE_WORDS = 6
# Salt so the stored hashes are this system's and not a lookup table for anyone else's.
_SHINGLE_SALT = b"brambleloop-originality-v1"
_WORD = re.compile(r"[a-z0-9]+")
_NUMBER = re.compile(r"\d+")

# Escalation thresholds. Chosen against the whole catalogue (tests/test_originality.py asserts
# no catalogue product escalates against either benchmark) and against synthetic copies.
WORDING_MATERIAL = 0.20          # share of OUR shingles found in the benchmark's
WORDING_MIN_SHARED = 20
FEATURE_MATERIAL = 0.60          # share of the benchmark's distinctive features we also have
FEATURE_MIN_SHARED = 3
CONSTRUCTION_MATERIAL = 0.70     # LCS of construction steps / benchmark's step count
NUMERIC_MIN_RUN = 5              # contiguous run of a benchmark's unusual sequence in our text
# Of one benchmark size's piece-level numbers, how many must recur among ours: at least this
# many, and at least this share of them. Four numbers in the right pieces is a coincidence
# nobody arrives at independently; three is arithmetic anybody might.
PIECE_NUMBERS_MIN = 4
PIECE_NUMBERS_SHARE = 0.75
UNUSUAL_FLOOR = 13               # numbers below this are too common to identify anything


def shingles(text: str, n: int = SHINGLE_WORDS) -> frozenset[str]:
    """Salted, truncated hashes of the word n-grams of `text`. Irreversible by design."""
    words = _WORD.findall((text or "").lower())
    out = set()
    for i in range(len(words) - n + 1):
        gram = " ".join(words[i:i + n]).encode()
        out.add(hashlib.sha256(_SHINGLE_SALT + gram).hexdigest()[:12])
    return frozenset(out)


def _is_arithmetic(seq) -> bool:
    d = {b - a for a, b in zip(seq, seq[1:])}
    return len(d) <= 1


@dataclass
class BenchmarkFingerprint:
    """What the similarity review compares against. Numbers, vocabulary keys and hashes."""

    ref: str
    title: str
    features: frozenset[str] = frozenset()
    construction: tuple[str, ...] = ()
    # Across-size sequences of one measurement, as a grader writes them. Only the unusual ones
    # (not arithmetic progressions) identify a pattern; `unusual_sequences` filters.
    size_sequences: dict[str, tuple[int, ...]] = field(default_factory=dict)
    # Per size, the piece-level numbers a maker works (foundations, piece totals).
    piece_numbers: dict[str, tuple[int, ...]] = field(default_factory=dict)
    wording: frozenset[str] = frozenset()

    def unusual_sequences(self) -> dict[str, tuple[int, ...]]:
        return {k: v for k, v in self.size_sequences.items()
                if len(v) >= NUMERIC_MIN_RUN and not _is_arithmetic(v)}


