# 4. Generation references (F-785)

# Path components that mark a file as somebody else's picture of their own work, or as a
# private reconstruction of a benchmark: the quarantine, seller/designer photography, and the
# research benchmarks' working directories.
_BENCHMARK_PATH_PARTS: frozenset[str] = frozenset({
    "benchmark_library", "seller_photos", "designer_photos", "competitor_photos",
    "benchmark_photos", "bench1", "bench2",
})
_BENCHMARK_NAME = re.compile(r"(seller|designer|competitor|benchmark)[-_ ]?(photo|image|img)",
                             re.I)


class ReferenceRefused(PermissionError):
    """A benchmark or seller image offered as a generation reference."""


def refuse_benchmark_reference(reference: str, *, env: dict[str, str] | None = None,
                               benchmark_hashes: set[str] | frozenset[str] | None = None
                               ) -> None:
    """Refuse a reference image whose provenance is a benchmark or a seller (F-785).

    Three independent tests, any one of which refuses: the file resolves inside the benchmark
    library's quarantine; its path or name marks it as seller/designer/competitor photography
    or a benchmark reconstruction; its bytes hash to a file recorded in a purchase manifest.
    """
    from ..teardown.library import library_root

    ref = str(reference or "")
    path = Path(ref)
    try:
        resolved = path.resolve()
    except (OSError, RuntimeError):
        resolved = path
    root = library_root(env)
    if resolved == root or root in resolved.parents:
        raise ReferenceRefused(
            f"{ref!r} is inside the benchmark library. A purchased pattern's images are for "
            f"private evaluation and are never a generation reference for Brambleloop "
            f"imagery (F-785)")
    parts = {p.lower() for p in resolved.parts} | {p.lower() for p in path.parts}
    marked = parts & _BENCHMARK_PATH_PARTS
    if marked or _BENCHMARK_NAME.search(path.name):
        raise ReferenceRefused(
            f"{ref!r} is marked as benchmark or seller imagery "
            f"({sorted(marked) or path.name}); a competitor's photograph may be studied and "
            f"never conditions a Brambleloop render (F-785)")
    if benchmark_hashes and resolved.is_file():
        digest = hashlib.sha256(resolved.read_bytes()).hexdigest()
        if digest in benchmark_hashes:
            raise ReferenceRefused(
                f"{ref!r} is byte-identical to a file in a benchmark purchase manifest "
                f"(sha256 {digest[:12]}); renamed benchmark imagery is still benchmark "
                f"imagery (F-785)")


def benchmark_file_hashes(db) -> frozenset[str]:
    """Every file hash in every purchase manifest (`BenchmarkProduct.files`)."""
    from sqlalchemy import select

    from ..core.models import BenchmarkProduct

    with db.session() as s:
        return frozenset(f.get("sha256") for r in s.scalars(select(BenchmarkProduct))
                         for f in (r.files or []) if f.get("sha256"))
