# Who may be named as a design's author. A design generated by something else -- a model
# paraphrasing a purchased PDF, an unlicensed import -- is not Brambleloop's own work however
# complete the rest of its record is.
OWN_AUTHORS: frozenset[str] = frozenset({"brambleloop"})


def brief_digest(brief: dict) -> str:
    """A stable 16-hex digest of the parameters a design was built from.

    Sorted JSON, so the same brief always gives the same digest and the digest changes exactly
    when the brief does.
    """
    payload = json.dumps(brief, sort_keys=True, default=str)
    return hashlib.sha256(payload.encode()).hexdigest()[:16]


def catalogue_provenance(concept_key: str, brief: dict, primitives: tuple[str, ...]):
    """The provenance a hand-engineered catalogue builder stamps on its CIR (F-783 backfill).

    `benchmarks_consulted` is empty on purpose and by audit: no catalogue builder imports
    `cir.benchmarks` or anything under `research/` (tests/test_cert_design.py and
    tests/test_originality.py hold that), so the honest record is that none was consulted.
    `at` is left unset: a timestamp would make the release hash differ on every build of an
    unchanged design.
    """
    from ..cir.model import Provenance

    return Provenance(concept_key=concept_key, brief_digest=brief_digest(brief),
                      primitives_used=tuple(primitives), benchmarks_consulted=(),
                      generated_by="brambleloop")


def provenance_gaps(prov) -> list[str]:
    """What a provenance record is missing. Empty means complete."""
    if prov is None:
        return ["provenance"]
    gaps = []
    if not str(getattr(prov, "concept_key", "") or "").strip():
        gaps.append("concept_key")
    if not str(getattr(prov, "brief_digest", "") or "").strip():
        gaps.append("brief_digest")
    if not tuple(getattr(prov, "primitives_used", ()) or ()):
        # The primitives are how the design was *made*. A record that names a concept and a
        # brief but no method says what the product is for and not where its numbers came
        # from, which is the half F-783 is about.
        gaps.append("primitives_used")
    if not str(getattr(prov, "generated_by", "") or "").strip():
        gaps.append("generated_by")
    return gaps


def provenance_findings(cir, *, ledger: "list[LedgerEntry] | None" = None) -> list[Finding]:
    """The certificate's originality-provenance stage (F-783, F-798, F-794, F-791).

    A `benchmark` CIR passes through: it is a record of someone else's work, never a product,
    and the specification stage already refuses one relabelled as ours.
    """
    if getattr(cir, "authored", "brambleloop") != "brambleloop":
        return []
    prov = getattr(cir, "provenance", None)
    if prov is None:
        return [Finding(
            ERROR, "PROVENANCE_MISSING",
            f"{cir.slug} is authored as Brambleloop's own but carries no design provenance: "
            f"nothing records the concept, brief, primitives or benchmarks it was built from. "
            f"A product is not release-ready on technical correctness alone (F-798); its "
            f"provenance must show the design is Brambleloop's own work (F-783)")]
    out: list[Finding] = []
    gaps = provenance_gaps(prov)
    if gaps:
        out.append(Finding(
            ERROR, "PROVENANCE_INCOMPLETE",
            f"{cir.slug}'s design provenance is missing {gaps}. Every field is what makes the "
            f"record checkable rather than asserted (F-783)"))
    author = str(getattr(prov, "generated_by", "") or "").strip().lower()
    if author and author not in OWN_AUTHORS:
        out.append(Finding(
            ERROR, "PROVENANCE_NOT_OURS",
            f"{cir.slug}'s provenance names {author!r} as its author; a release authored as "
            f"Brambleloop's must be generated by {sorted(OWN_AUTHORS)} (F-798)"))
    consulted = tuple(getattr(prov, "benchmarks_consulted", ()) or ())
    if consulted:
        entries = ledger if ledger is not None else declared_ledger(prov.concept_key)
        if not entries:
            out.append(Finding(
                ERROR, "DESIGN_LEDGER_MISSING",
                f"{cir.slug} consulted benchmarks {list(consulted)} and has no "
                f"design-difference ledger: what was learned, what changed, why it is better "
                f"and what was designed independently must be recorded (F-794)"))
        else:
            verdict = redesign_verdict(entries, consulted)
            if not verdict["passed"]:
                out.append(Finding(
                    ERROR, "REDESIGN_NOT_MEANINGFUL",
                    f"{cir.slug}: " + "; ".join(verdict["reasons"][:4]) + " (F-791)"))
    return out


