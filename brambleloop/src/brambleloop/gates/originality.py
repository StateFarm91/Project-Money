def _ops(nodes):
    for n in nodes or ():
        inner = getattr(n, "ops", None)
        if inner is not None:
            yield ("repeat", n)
            yield from _ops(inner)
        else:
            yield ("op", n)


def candidate_features(cir) -> frozenset[str]:
    """The candidate's distinctive features, in the benchmarks' vocabulary."""
    names = " ".join(c.name.lower() for c in cir.components)
    title = f"{cir.slug} {cir.title}".lower()
    feats: set[str] = set()
    if "cardigan" in title:
        feats.add("cardigan")
    if "hood" in names:
        feats.add("hood")
    if "pocket" in names:
        feats.add("patch_pockets")
    if "button" in names or any("button" in (m.name or "").lower() for m in cir.materials):
        feats.add("buttons")
    if any(getattr(c, "grain", "up") == "across" for c in cir.components):
        feats.add("side_to_side_grain")
    if "sleeve" in names and any("sleeve" in (s.piece_a + s.piece_b).lower()
                                 for s in cir.assembly):
        feats.add("sewn_sleeves")
    if "yoke" in names and "sleeve" not in names:
        feats.add("built_in_sleeves")
    body_pieces = [c for c in cir.components if "body" in c.name.lower()]
    if len(body_pieces) == 1 and "cardigan" in title:
        feats.add("one_piece_body")
    if "child" in title or "baby" in title or "mini" in title:
        feats.add("child_sizing")
    for comp in cir.components:
        for row in comp.rows:
            kinds = list(_ops(row.ops))
            stitches = {getattr(n, "stitch", None) for k, n in kinds if k == "op"}
            if stitches & _STAR:
                feats.add("star_stitch_body")
            if any(getattr(n, "spans", 0) for k, n in kinds if k == "op"):
                feats.add("bridged_armholes")
            for k, n in kinds:
                if k == "repeat":
                    loops = {getattr(o, "loop", "both") for o in n.ops
                             if getattr(o, "stitch", None)}
                    if {"front", "back"} <= loops:
                        feats.add("loop_alternating_texture")
            back_runs = [n for k, n in kinds if k == "op" and getattr(n, "loop", "") == "back"
                         and getattr(n, "count", 1) >= 5]
            if back_runs and len(kinds) > 1 and "body" in comp.name.lower():
                feats.add("integral_edge_rib")
            if back_runs and any(w in comp.name.lower() for w in
                                 ("band", "cuff", "collar", "rib", "hem")):
                feats.add("blo_ribbed_bands")
    return frozenset(feats)


# Component-name words -> the construction vocabulary the benchmarks are written in.
_STEP_WORDS: tuple[tuple[str, str], ...] = (
    ("hem", "hem_band"), ("pocket", "pockets"), ("hood", "hood"), ("cuff", "cuffs"),
    ("collar", "collar_band"), ("neck", "neck_band"), ("yoke", "yoke_with_sleeves"),
    ("sleeve", "sleeves"), ("front", "fronts"), ("back", "back_body"), ("button", "buttons"),
    ("body", "body"), ("armhole", "armhole"),
)


def candidate_construction(cir) -> tuple[str, ...]:
    steps: list[str] = []
    for comp in cir.components:
        low = comp.name.lower()
        for word, step in _STEP_WORDS:
            if word in low:
                if not steps or steps[-1] != step:
                    steps.append(step)
                break
    return tuple(steps)


def _lcs(a, b) -> int:
    prev = [0] * (len(b) + 1)
    for x in a:
        cur = [0]
        for j, y in enumerate(b):
            cur.append(prev[j] + 1 if x == y else max(prev[j + 1], cur[j]))
        prev = cur
    return prev[-1]


def candidate_piece_numbers(cir) -> frozenset[int]:
    """Piece-level numbers: each piece's foundation and its first, last and widest count."""
    from ..cir.compiler import compile_cir

    result = compile_cir(cir)
    out: set[int] = set()
    for comp in cir.components:
        produced = [r.produced for r in result.rows if r.component == comp.name
                    and r.produced is not None]
        for v in [comp.foundation] + ([produced[0], produced[-1], max(produced)]
                                      if produced else []):
            if v and v >= UNUSUAL_FLOOR:
                out.add(int(v))
    return frozenset(out)


def _contains_run(stream: list[int], seq: tuple[int, ...], run: int) -> bool:
    if len(seq) < run:
        return False
    windows = {tuple(seq[i:i + run]) for i in range(len(seq) - run + 1)
               if not _is_arithmetic(seq[i:i + run])}
    if not windows:
        return False
    for i in range(len(stream) - run + 1):
        if tuple(stream[i:i + run]) in windows:
            return True
    return False


def compare(cir, benchmark: BenchmarkFingerprint, *, pattern_text: str | None = None) -> dict:
    """One candidate against one benchmark, dimension by dimension."""
    dims: dict[str, dict] = {}

    # Wording n-grams. Unmeasured when either side has no text: absence of a fingerprint is
    # not evidence of absence of copying.
    ours = shingles(pattern_text or "") if pattern_text else frozenset()
    if not benchmark.wording or not ours:
        dims["wording"] = {"verdict": "unmeasured",
                           "why": ("no fingerprint of the benchmark's wording has been "
                                   "captured" if not benchmark.wording else
                                   "no candidate text to compare")}
    else:
        shared = len(ours & benchmark.wording)
        share = shared / len(ours)
        dims["wording"] = {"verdict": ("material" if share >= WORDING_MATERIAL
                                       and shared >= WORDING_MIN_SHARED else "clear"),
                           "shared_shingles": shared, "share_of_ours": round(share, 3)}

    # Unusual numeric sequences: a benchmark's non-arithmetic across-size run in our text, or
    # most of one size's piece-level numbers in our pieces.
    hits: list[str] = []
    stream = [int(n) for n in _NUMBER.findall(pattern_text or "")]
    for name, seq in benchmark.unusual_sequences().items():
        if stream and _contains_run(stream, seq, NUMERIC_MIN_RUN):
            hits.append(f"across-size {name} run")
    mine = candidate_piece_numbers(cir)
    for size, nums in benchmark.piece_numbers.items():
        found = sorted(set(nums) & mine)
        need = max(PIECE_NUMBERS_MIN, math.ceil(PIECE_NUMBERS_SHARE * len(set(nums))))
        if len(found) >= need:
            hits.append(f"size {size} piece numbers {found}")
    dims["numeric"] = {"verdict": "material" if hits else "clear", "hits": hits[:6]}

    # Distinctive feature combination.
    feats = candidate_features(cir)
    shared_f = sorted(feats & benchmark.features)
    share_f = len(shared_f) / len(benchmark.features) if benchmark.features else 0.0
    feature_material = share_f >= FEATURE_MATERIAL and len(shared_f) >= FEATURE_MIN_SHARED
    dims["features"] = {"verdict": "material" if feature_material else "clear",
                        "shared": shared_f, "share_of_theirs": round(share_f, 3)}

    # Construction sequence.
    steps = candidate_construction(cir)
    lcs = _lcs(steps, benchmark.construction) if benchmark.construction else 0
    share_c = lcs / len(benchmark.construction) if benchmark.construction else 0.0
    dims["construction"] = {"verdict": "material" if share_c >= CONSTRUCTION_MATERIAL
                            else "clear", "ours": list(steps),
                            "share_of_theirs": round(share_c, 3)}

    # Features and construction together are what "the same design" means; either alone is a
    # genre (every cardigan has fronts and sleeves). Wording or numbers alone are a copy.
    material = [d for d in ("wording", "numeric") if dims[d]["verdict"] == "material"]
    if feature_material and dims["construction"]["verdict"] == "material":
        material += ["features", "construction"]
    return {"benchmark": benchmark.ref, "title": benchmark.title, "dimensions": dims,
            "material": material,
            "unmeasured": [d for d, v in dims.items() if v["verdict"] == "unmeasured"]}


SIMILARITY_ACTION = "originality.similarity_review"


def similarity_review(cir, *, pattern_text: str | None = None, db=None,
                      benchmarks: list[BenchmarkFingerprint] | None = None) -> dict:
    """Compare a candidate with every purchased benchmark (F-795).

    `escalate` is True when any benchmark overlaps materially; the product goes back for
    redesign with the benchmarks and dimensions named. Benchmarks are the code-encoded pair,
    plus every teardown fingerprint in `db` when one is given (a stored fingerprint for the
    same ref adds its wording to the code one rather than replacing it).
    """
    pool = {b.ref: b for b in (benchmarks if benchmarks is not None else code_benchmarks())}
    if db is not None and benchmarks is None:
        for fp in fingerprints_from_db(db):
            have = pool.get(fp.ref)
            if have is None:
                pool[fp.ref] = fp
            else:
                have.wording = have.wording | fp.wording
    comparisons = [compare(cir, b, pattern_text=pattern_text) for b in pool.values()]
    escalated = [c for c in comparisons if c["material"]]
    return {"slug": cir.slug, "benchmarks_compared": sorted(pool),
            "escalate": bool(escalated),
            "escalated": [{"benchmark": c["benchmark"], "dimensions": c["material"]}
                          for c in escalated],
            "unmeasured": sorted({f"{c['benchmark']}:{d}" for c in comparisons
                                  for d in c["unmeasured"]}),
            "comparisons": comparisons}


def similarity_findings(cir, *, pattern_text: str | None = None) -> list[Finding]:
    """The certificate's similarity stage: material overlap is an ERROR, never a footnote."""
    if getattr(cir, "authored", "brambleloop") != "brambleloop":
        return []
    review = similarity_review(cir, pattern_text=pattern_text)
    out = [Finding(ERROR, "SIMILARITY_ESCALATED",
                   f"{cir.slug} overlaps materially with {e['benchmark']} on "
                   f"{e['dimensions']}: escalated for redesign (F-795). A purchased benchmark "
                   f"informs research; the sellable design must be Brambleloop's own")
           for e in review["escalated"]]
    prov = getattr(cir, "provenance", None)
    if prov is not None and tuple(prov.benchmarks_consulted or ()) and review["unmeasured"]:
        # Only for a competitor-informed design: there the unmeasured wording comparison is
        # the one a reviewer most needs to know was not made.
        out.append(Finding(WARNING, "SIMILARITY_UNMEASURED",
                           f"{cir.slug}: not compared on {review['unmeasured'][:4]}; "
                           f"capture the benchmark's wording fingerprint at teardown"))
    return out


def release_findings(cir, *, pattern_text: str | None = None) -> list[Finding]:
    """Everything this module contributes to a release certificate, in one call."""
    return provenance_findings(cir) + similarity_findings(cir, pattern_text=pattern_text)


