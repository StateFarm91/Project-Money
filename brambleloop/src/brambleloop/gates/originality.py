def record_ledger(db, concept_key: str, entries, *, recorded_by: str = "creative_director"
                  ) -> dict:
    """Persist a concept's ledger (one row per benchmark) with the gate's verdict on it."""
    from datetime import datetime, timezone

    from sqlalchemy import select

    from ..core.models import DesignDifferenceLedger

    rows = [e if isinstance(e, LedgerEntry) else LedgerEntry.from_dict(e) for e in entries]
    verdict = redesign_verdict(rows)
    with db.session() as s:
        for e in rows:
            row = s.scalar(select(DesignDifferenceLedger).where(
                DesignDifferenceLedger.concept_key == concept_key,
                DesignDifferenceLedger.benchmark_ref == e.benchmark_ref))
            if row is None:
                row = DesignDifferenceLedger(concept_key=concept_key,
                                             benchmark_ref=e.benchmark_ref)
                s.add(row)
            row.learned = e.learned
            row.changed = [dict(c) for c in e.changed]
            row.why_better = e.why_better
            row.independent_aspects = list(e.independent_aspects)
            row.verdict = verdict["per_benchmark"].get(e.benchmark_ref or "unnamed benchmark",
                                                       {})
            row.passed = bool(verdict["passed"])
            row.recorded_by = recorded_by
            row.recorded_at = datetime.now(timezone.utc)
    return verdict


