# Aspects whose change distinguishes a product materially (F-790's improvement list, less the
# ones F-791 names as insufficient on their own).
MATERIAL_ASPECTS: tuple[str, ...] = (
    "fit", "proportions", "stitch_system", "shaping", "construction", "grading", "sizing",
    "features", "finishing", "silhouette",
)
# F-791, verbatim in vocabulary: "merely changing colour, yarn, wording, size labels, button
# count, small dimensions or a few rows is not sufficient".
SUPERFICIAL_ASPECTS: tuple[str, ...] = (
    "colour", "yarn", "wording", "size_labels", "button_count", "small_dimensions", "few_rows",
)
# A dimension change below this is a small dimension whatever it is labelled.
SMALL_DIMENSION_PCT = 10.0
# A row-count change at or below this is "a few rows" whatever it is labelled.
FEW_ROWS = 4
# How many material decisions, in how many distinct aspects, a competitor-informed design needs.
MIN_MATERIAL_DECISIONS = 2
MIN_MATERIAL_ASPECTS = 2
MIN_WHY_WORDS = 4

_SUPERFICIAL_WORDS = re.compile(
    r"\b(colou?rs?|colou?rway|palette|shade|hue|yarn|fibre|fiber|brand|wording|reworded|"
    r"rephrased|renamed|label|labels|button|buttons|a few rows|rows? (?:added|removed)|"
    r"(?:added|removed|dropped) (?:one|two|three|four|\d) rows?|slightly|a little)\b")
_MATERIAL_WORDS = re.compile(
    r"\b(fit|ease|proportion|proportions|stitch system|stitch pattern|texture|construction|"
    r"constructed|top-down|bottom-up|side-to-side|in the round|seamless|seamed|raglan|yoke|"
    r"set-in|drop-shoulder|shaping|shaped|decrease|increase|grading|graded|size range|"
    r"body table|silhouette|hood|pocket|collar|closure|placket|finishing|edging|feature|"
    r"features|cropped|oversized|length)\b")


@dataclass
class LedgerEntry:
    """One benchmark's line in a design-difference ledger (F-794)."""

    benchmark_ref: str
    learned: str
    # Each change: {"aspect": one of MATERIAL_ASPECTS or SUPERFICIAL_ASPECTS, "what": str,
    # optional "magnitude_pct": float (dimension changes), optional "rows_delta": int}.
    changed: list[dict] = field(default_factory=list)
    why_better: str = ""
    independent_aspects: list[str] = field(default_factory=list)

    @staticmethod
    def from_dict(d: dict) -> "LedgerEntry":
        return LedgerEntry(benchmark_ref=str(d.get("benchmark_ref") or ""),
                           learned=str(d.get("learned") or ""),
                           changed=[dict(c) for c in (d.get("changed") or [])],
                           why_better=str(d.get("why_better") or ""),
                           independent_aspects=[str(a) for a in
                                                (d.get("independent_aspects") or [])])

    def to_dict(self) -> dict:
        return {"benchmark_ref": self.benchmark_ref, "learned": self.learned,
                "changed": [dict(c) for c in self.changed], "why_better": self.why_better,
                "independent_aspects": list(self.independent_aspects)}


def classify_change(change: dict) -> tuple[str, str]:
    """(effective aspect, "material" | "superficial" | "unclassified") for one change.

    The label is the designer's claim; the classification is this function's. A change
    labelled material is demoted when its own magnitude or wording says otherwise.
    """
    aspect = str(change.get("aspect") or "").strip().lower()
    what = str(change.get("what") or "").lower()
    if aspect in SUPERFICIAL_ASPECTS:
        return aspect, "superficial"
    if aspect not in MATERIAL_ASPECTS:
        return aspect or "unstated", "unclassified"
    pct = change.get("magnitude_pct")
    if pct is not None and abs(float(pct)) < SMALL_DIMENSION_PCT:
        return "small_dimensions", "superficial"
    rows = change.get("rows_delta")
    if rows is not None and abs(int(rows)) <= FEW_ROWS and pct is None:
        return "few_rows", "superficial"
    if _SUPERFICIAL_WORDS.search(what) and not _MATERIAL_WORDS.search(what):
        return aspect, "superficial"
    if not what.strip():
        return aspect, "unclassified"
    return aspect, "material"


def redesign_verdict(entries, consulted=()) -> dict:
    """Whether a ledger documents original design decisions that materially distinguish the
    product from every benchmark consulted (F-791). Deterministic; never asks a model."""
    rows = [e if isinstance(e, LedgerEntry) else LedgerEntry.from_dict(e) for e in entries]
    reasons: list[str] = []
    per_benchmark: dict[str, dict] = {}
    by_ref = {e.benchmark_ref: e for e in rows}
    for ref in consulted:
        if ref not in by_ref:
            reasons.append(f"benchmark {ref!r} was consulted and has no ledger entry")
    for e in rows:
        where = e.benchmark_ref or "unnamed benchmark"
        material, superficial, unclassified = [], [], []
        for c in e.changed:
            aspect, kind = classify_change(c)
            {"material": material, "superficial": superficial,
             "unclassified": unclassified}[kind].append(aspect)
        if not e.benchmark_ref:
            reasons.append("a ledger entry names no benchmark_ref")
        if not e.learned.strip():
            reasons.append(f"{where}: nothing recorded as learned")
        if len(e.why_better.split()) < MIN_WHY_WORDS:
            reasons.append(f"{where}: why_better does not say why the changes improve it")
        if not e.independent_aspects:
            reasons.append(f"{where}: no aspect recorded as independently designed")
        if len(material) < MIN_MATERIAL_DECISIONS or len(set(material)) < MIN_MATERIAL_ASPECTS:
            reasons.append(
                f"{where}: {len(material)} material change(s) in {sorted(set(material))}; "
                f"needs {MIN_MATERIAL_DECISIONS} in {MIN_MATERIAL_ASPECTS}+ of "
                f"{list(MATERIAL_ASPECTS)}. Superficial only: {sorted(superficial)} -- colour, "
                f"yarn, wording, size labels, button count, small dimensions or a few rows "
                f"do not distinguish a design")
        if unclassified:
            reasons.append(f"{where}: changes with no recognised aspect or description: "
                           f"{sorted(unclassified)}")
        per_benchmark[where] = {"material": sorted(material), "superficial": sorted(superficial),
                                "unclassified": sorted(unclassified)}
    if not rows:
        reasons.append("the ledger is empty")
    return {"passed": not reasons, "reasons": reasons, "per_benchmark": per_benchmark}


