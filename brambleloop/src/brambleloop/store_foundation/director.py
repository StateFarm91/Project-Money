"""The Storefront Director as an operational agent (Master Plan v1.2 sections 6 and 16).

Section 6: "Storefront Director owns banner, icon, About, policies, sections, announcement,
thumbnails and grid coherence." `brand.storefront` held that role's *copy*; this module is the
role's *work*, run by the registered agent `storefront_director` (agents.registry) inside the
existing Store / Commerce charter:

* `review(db)` -- read the shop state we already hold (the stored getShop / shop_sync
  readings and the owner's dated observations, `live_state.snapshot`), evaluate every surface
  against the brand rules (`store_foundation.lint`, `copy_v2.BANNED_EVERYWHERE`, D-FB-18's
  populated-categories-only navigation) and Etsy's published constraints, and say for each
  surface who can act: the agent (an Etsy write API exists), the owner (none does), or nobody
  (owner-configured, protected; or EU-only).
* `build_proposals(db)` -- deterministic drafts from our own sources only (copy_v2,
  commerce.shop_package, store_foundation.content/navigation), each validated by the same rules.
  Nothing is generated by a model and nothing comes from a competitor: every draft names the
  module attribute it came from.
* Every proposal is a recorded row (`operating_readings` kind `storefront.proposal`, keyed by
  the digest of its exact change). A proposal with an Etsy write API is applied only by
  `store.update` (store_operator, PUBLISH class, protected), which writes nothing in SHADOW or
  without the owner's sealed grant for that exact change (`ops.storefront_authority`).

No network call and no Etsy write happens in this module.
"""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from typing import Any

AGENT = "storefront_director"
REVIEW_JOB = "storefront.review"
DRAFT_JOB = "content.draft"
APPLY_JOB = "store.update"
APPLY_AGENT = "store_operator"
REVIEW_READING = "storefront.review"
PROPOSAL_KIND = "storefront.proposal"

AGENT_PROPOSAL = "AGENT_PROPOSAL"      # an Etsy write API exists: proposal -> store.update
OWNER_STEP = "OWNER_STEP"              # no write API: the owner pastes the drafted text
PROTECTED = "PROTECTED"                # owner-configured or EU-only: never written
OK = "OK"
UNKNOWN = "UNKNOWN"

# Our field key -> (Etsy operation or None, label). Text fields live in live_state.FIELDS.
API_TEXT_FIELDS: dict[str, str] = {"announcement": "updateShop",
                                   "sale_message": "updateShop",
                                   "digital_sale_message": "updateShop"}
# Surfaces with no Etsy write API (intel.etsy_surfaces / AGENT_AUDIT finding 7).
OWNER_ONLY: dict[str, str] = {
    "shop_banner": "Shop home editor > Banner (no API)",
    "shop_icon": "Settings > Your shop > Logo (no API)",
    "about_story": "Shop home editor > About (no API, owner-configured)",
    "laura_member_profile": "Shop team > member bio (no API, owner-configured)",
    "policy_shipping": "Settings > Policy Settings > delivery (no API)",
    "policy_refunds": "Settings > Policy Settings > returns (no API)",
    "policy_privacy": "Settings > Policy Settings > privacy (no API)",
}
ANNOUNCEMENT_MAX = 160          # brand.storefront.ANNOUNCEMENT_MAX (internal style cap)
MESSAGE_MAX = 5000              # no Etsy figure published; kept to the About cap
SECTIONS_MAX = 20               # Etsy help 360000345048
LIVE_FRESH_DAYS = 7


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _json(v) -> str:
    return json.dumps(v, sort_keys=True, separators=(",", ":"), ensure_ascii=True, default=str)


def digest(change: dict) -> str:
    return hashlib.sha256(_json(change).encode()).hexdigest()


def _norm(t: Any) -> str:
    return " ".join(str(t or "").split()).casefold()


# ---- validation (brand rules + Etsy constraints) ------------------------------------------


def text_problems(text: str, *, surface: str, db=None, limit: int | None = None) -> list[str]:
    """Why `text` may not go on the live shop: truth lint, banned words, empty categories,
    length. Deterministic; an empty list means it may be proposed."""
    from . import copy_v2, lint, navigation

    t = str(text or "")
    out: list[str] = []
    if not t.strip():
        out.append(f"{surface}: blank")
        return out
    for f in lint.lint(t, surface=surface, voice=False):
        if f.get("kind") == lint.TRUTH:
            out.append(f"truth: {f['detail'][:160]}")
    low = f" {t.lower()} "
    for w in copy_v2.BANNED_EVERYWHERE:
        if f" {w} " in low or f" {w}." in low or f" {w}," in low:
            out.append(f"brand: banned word {w!r} in customer copy")
    try:
        empty = navigation.empty_categories_named(t, db)
    except Exception:  # noqa: BLE001 - unreadable navigation blocks rather than passes
        empty = ["UNKNOWN (navigation unreadable)"]
    if empty and surface != "shop_section":
        out.append(f"brand: names categories with no product yet {empty} (D-FB-18 item 3)")
    if limit is not None and len(t) > limit:
        out.append(f"{surface}: {len(t)} characters exceeds {limit}")
    return out


def validate_change(db, change: dict, *, surface: str = "") -> list[str]:
    """The checks `store.update` and the owner grant re-run on a recorded change."""
    from ..integrations.etsy import SECTION_TITLE_MAX
    from . import live_state

    op = str((change or {}).get("operation") or "")
    if op == "updateShop":
        fields = dict(change.get("fields") or {})
        if not fields:
            return ["updateShop with no fields"]
        out = []
        for k, v in fields.items():
            if k not in API_TEXT_FIELDS:
                out.append(f"{k}: not an agent-writable updateShop field")
                continue
            why = live_state.write_refusal(k)
            if why and ("owner on the live shop" in why or "EU-located" in why):
                out.append(why)
            out += text_problems(v, surface=k, db=db,
                                 limit=ANNOUNCEMENT_MAX if k == "announcement" else MESSAGE_MAX)
        return out
    if op == "createShopSection":
        title = str(change.get("title") or "")
        out = text_problems(title, surface="shop_section", db=db, limit=SECTION_TITLE_MAX)
        from . import navigation

        public = {_norm(s["name"]) for s in navigation.public_nav(db)}
        if _norm(title) not in public:
            out.append(f"section {title!r} has no product yet (D-FB-18 item 3)")
        return out
    return [f"{op or 'unknown operation'}: the Storefront Director proposes no such change"]


# ---- reading the shop state ---------------------------------------------------------------


def _live_sections(db, now: datetime) -> dict:
    """Section titles from the newest shop_sync reading, or UNKNOWN."""
    from ..runtime.etsy_ops import latest_reading
    from . import live_state

    r = latest_reading(db, live_state.SYNC_READING) if db is not None else None
    if not r or not r.get("observed_at"):
        return {"state": UNKNOWN, "titles": [], "why": "no store.shop_sync reading"}
    age = (now.timestamp() - float(r["observed_at"])) / 86400.0
    titles = [str(x.get("title") or "") for x in (r.get("sections") or []) if isinstance(x, dict)]
    return {"state": "FRESH" if 0 <= age <= LIVE_FRESH_DAYS else "STALE",
            "titles": titles, "age_days": round(age, 2)}


def drafts(db=None) -> dict[str, dict]:
    """Every draft the Director can propose, with the source it came from (never a model,
    never a competitor)."""
    from ..commerce import shop_package
    from . import content, navigation

    surf = content.build(db)
    api = shop_package.api_shop_fields()
    out = {
        "announcement": {"text": surf["announcement"].value,
                         "source": "store_foundation.content['announcement'] "
                                   "(copy_v2.ANNOUNCEMENT / applied takeover)"},
        "sale_message": {"text": api.get("sale_message", ""),
                         "source": "commerce.shop_package.api_shop_fields()['sale_message']"},
        "digital_sale_message": {"text": api.get("digital_sale_message", ""),
                                 "source": "commerce.shop_package.api_shop_fields()"
                                           "['digital_sale_message']"},
        "policy_shipping": {"text": surf["policy_delivery"].value,
                            "source": "store_foundation.copy_v2.DELIVERY"},
        "policy_refunds": {"text": surf["policy_returns"].value,
                           "source": "store_foundation.copy_v2.RETURNS"},
        "policy_privacy": {"text": surf["policy_privacy"].value,
                           "source": "store_foundation.copy_v2.PRIVACY + PRIVACY_ADDENDUM"},
    }
    out["sections"] = {"titles": [s["name"] for s in navigation.public_nav(db)],
                       "source": "store_foundation.navigation.public_nav (copy_v2.SECTIONS, "
                                 "populated categories only)"}
    return out


def review(db, *, now: datetime | None = None) -> dict:
    """Evaluate every storefront surface. Pure reads; returns the review record."""
    from . import live_state

    now = now or _now()
    snap = live_state.snapshot(db, now=now)
    d = drafts(db)
    rows: list[dict] = []

    def row(surface, actor, status, why, **kw):
        rows.append({"surface": surface, "actor": actor, "status": status, "why": why, **kw})

    for f in ("shop_title", "about_story", "laura_member_profile", "laura_member_role",
              "shop_name"):
        s = snap.get(f) or {}
        row(f, PROTECTED, s.get("state", UNKNOWN),
            "owner-configured on the live shop (2026-10-06): never written by software",
            live_state=s.get("state", UNKNOWN))
    for f in API_TEXT_FIELDS:
        s = snap.get(f)
        draft = d[f]["text"]
        if s is None:            # sale_message is not a live_state field: no reading of it
            row(f, AGENT_PROPOSAL, UNKNOWN, "no stored reading of this field", live_state=UNKNOWN,
                draft_problems=text_problems(draft, surface=f, db=db))
            continue
        state, value = s.get("state", UNKNOWN), s.get("value")
        live_problems = ([] if not str(value or "").strip() else
                         text_problems(value, surface=f"live {f}", db=db))
        if state == UNKNOWN:
            status, why = UNKNOWN, "no live reading"
        elif not str(value or "").strip():
            status, why = "MISSING", "blank on the live shop"
        elif _norm(value) == _norm(draft):
            status, why = OK, "live matches the certified draft"
        elif live_problems:
            status, why = "LIVE_FAILS_RULES", "; ".join(live_problems)[:300]
        else:
            status, why = "DIFFERS", "live differs from the repo draft (owner's text stands)"
        row(f, AGENT_PROPOSAL, status, why, live_state=state,
            draft_problems=text_problems(draft, surface=f, db=db,
                                         limit=ANNOUNCEMENT_MAX if f == "announcement"
                                         else MESSAGE_MAX))
    live = _live_sections(db, now)
    want = d["sections"]["titles"]
    have = {_norm(t) for t in live["titles"]}
    missing = [t for t in want if _norm(t) not in have] if live["state"] == "FRESH" else []
    row("sections", AGENT_PROPOSAL,
        UNKNOWN if live["state"] != "FRESH" else ("MISSING" if missing else OK),
        live.get("why") or (f"missing {missing}" if missing else "every populated category "
                                                                  "has a section"),
        live_state=live["state"], missing=missing, live_titles=live["titles"])
    # F-365 (W4-AGENTS C1): a Baby & Kids collection is proposed only when catalogue depth
    # justifies it (creative.children.architecture). Advisory: the section name is not yet in
    # the brand's section architecture, so no createShopSection is drafted for it.
    try:
        from ..creative import children

        arch = children.architecture(db)
        row("baby_kids_collection", "ADVISORY",
            "PROPOSED" if arch.get("propose_collection") else "NOT_YET",
            arch.get("why") or f"{arch.get('children_certified')} children's products: add a "
                                f"Baby & Kids section to the brand architecture",
            live_state=UNKNOWN, navigation=arch.get("navigation"))
    except Exception as exc:  # noqa: BLE001 - one advisory never stops the review
        row("baby_kids_collection", "ADVISORY", UNKNOWN, f"unreadable: {type(exc).__name__}",
            live_state=UNKNOWN)
    for f, where in OWNER_ONLY.items():
        s = snap.get(f) or {}
        value = s.get("value")
        blank = (value is None or (isinstance(value, str) and not value.strip())
                 or (isinstance(value, dict) and value.get("present") is False))
        status = UNKNOWN if s.get("state", UNKNOWN) == UNKNOWN else ("MISSING" if blank else OK)
        row(f, OWNER_STEP, status, where, live_state=s.get("state", UNKNOWN))
    # LISTREADY E3: Etsy holds whatever value policy_additional has; it is not a check, the
    # company never writes it and never asks the owner to clear it. Reported, never a gap.
    pa = snap.get("policy_additional") or {}
    row("policy_additional", PROTECTED, "NOT_A_CHECK",
        "Etsy holds this value (LISTREADY E3); the company never writes it (EU-only field) "
        "and asks nobody to change it", live_state=pa.get("state", UNKNOWN))
    counts: dict[str, int] = {}
    for r in rows:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    agent_gaps = [r["surface"] for r in rows if r["actor"] == AGENT_PROPOSAL
                  and r["status"] in ("MISSING", "LIVE_FAILS_RULES")]
    owner_gaps = [r["surface"] for r in rows if r["status"] == "MISSING"
                  and r["actor"] != AGENT_PROPOSAL]
    return {"at": now.isoformat(), "agent": AGENT, "surfaces": rows, "counts": counts,
            "agent_gaps": agent_gaps, "owner_gaps": owner_gaps,
            "unknown": [r["surface"] for r in rows if r["status"] == UNKNOWN],
            "writes_performed": 0, "etsy_calls": 0}


# ---- proposals ----------------------------------------------------------------------------


def build_proposals(db, rev: dict | None = None) -> list[dict]:
    """Deterministic, validated proposals for every gap the review found."""
    rev = rev or review(db)
    d = drafts(db)
    out: list[dict] = []
    by = {r["surface"]: r for r in rev["surfaces"]}
    for f in API_TEXT_FIELDS:
        r = by.get(f) or {}
        if r.get("status") not in ("MISSING", "LIVE_FAILS_RULES", "DIFFERS"):
            continue
        change = {"operation": "updateShop", "fields": {f: d[f]["text"]}}
        out.append(_proposal(db, f, change, d[f]["source"], api=True,
                             replaces_live_text=r.get("status") != "MISSING"))
    sec = by.get("sections") or {}
    for title in sec.get("missing") or []:
        change = {"operation": "createShopSection", "title": title}
        out.append(_proposal(db, "shop_section", change, d["sections"]["source"], api=True))
    for f in ("policy_shipping", "policy_refunds", "policy_privacy"):
        if (by.get(f) or {}).get("status") == "MISSING":
            text = d[f]["text"]
            out.append({"surface": f, "api_writable": False, "kind": OWNER_STEP,
                        "where": OWNER_ONLY[f], "text": text, "source": d[f]["source"],
                        "problems": text_problems(text, surface=f, db=db),
                        "digest": digest({"owner_step": f, "text": text})})
    return out


def _proposal(db, surface: str, change: dict, source: str, *, api: bool,
              replaces_live_text: bool = False) -> dict:
    problems = validate_change(db, change, surface=surface)
    return {"surface": surface, "api_writable": api, "kind": AGENT_PROPOSAL,
            "change": change, "source": source, "problems": problems,
            "valid": not problems, "replaces_live_text": replaces_live_text,
            "digest": digest(change), "auto_apply": False,
            "applied_by": f"{APPLY_JOB} ({APPLY_AGENT}) under ops.storefront_authority"}


def record_proposal(db, p: dict, *, now: datetime | None = None) -> bool:
    """Store one proposal (idempotent on its digest). True when newly recorded."""
    from sqlalchemy import select

    from ..core.models import AuditLog, OperatingReading

    now = now or _now()
    key = p["digest"][:20]
    with db.session() as s:
        if s.scalar(select(OperatingReading.id).where(OperatingReading.kind == PROPOSAL_KIND,
                                                      OperatingReading.period_key == key)):
            return False
        s.add(OperatingReading(kind=PROPOSAL_KIND, period_key=key, at=now,
                               payload={**p, "recorded_at": now.isoformat(),
                                        "state": "proposed"}))
        s.add(AuditLog(actor=AGENT, action="storefront.proposal", artifact=p["surface"],
                       detail={"digest": p["digest"], "api_writable": p["api_writable"],
                               "valid": p.get("valid", not p.get("problems")),
                               "source": p.get("source")}))
    return True


def proposal(db, ident: str) -> dict | None:
    from sqlalchemy import select

    from ..core.models import OperatingReading

    with db.session() as s:
        row = s.scalar(select(OperatingReading).where(
            OperatingReading.kind == PROPOSAL_KIND,
            OperatingReading.period_key == str(ident or "")[:20]))
        return dict(row.payload or {}) if row is not None else None


def set_proposal_state(db, ident: str, state: str, **detail) -> None:
    from sqlalchemy import select

    from ..core.models import OperatingReading

    with db.session() as s:
        row = s.scalar(select(OperatingReading).where(
            OperatingReading.kind == PROPOSAL_KIND,
            OperatingReading.period_key == str(ident)[:20]))
        if row is not None:
            row.payload = {**dict(row.payload or {}), "state": state,
                           "state_detail": {k: v for k, v in detail.items()}}


def proposals(db, *, limit: int = 50) -> list[dict]:
    from sqlalchemy import desc, select

    from ..core.models import OperatingReading

    with db.session() as s:
        return [dict(r.payload or {}) for r in s.scalars(
            select(OperatingReading).where(OperatingReading.kind == PROPOSAL_KIND)
            .order_by(desc(OperatingReading.id)).limit(limit))]


def summary(db) -> dict:
    """Provider for Laura's executive loop (laura.executive.loop.PROVIDERS)."""
    from ..runtime.etsy_ops import latest_reading

    r = latest_reading(db, REVIEW_READING)
    if not r:
        return {"status": UNKNOWN, "reason": "no storefront review yet: the Storefront "
                                             "Director has not read the shop",
                "as_of": None}
    if r.get("agent_gaps"):
        return {"status": "DEGRADED", "as_of": r.get("at"),
                "reason": f"storefront gaps the agent can propose: {r['agent_gaps']}"}
    if r.get("unknown") and len(r["unknown"]) == len(r.get("surfaces") or []):
        return {"status": UNKNOWN, "as_of": r.get("at"), "reason": "no live shop reading"}
    return {"status": "OK", "as_of": r.get("at"),
            "reason": f"no agent-doable gap; owner steps open: {r.get('owner_gaps') or []}"}
