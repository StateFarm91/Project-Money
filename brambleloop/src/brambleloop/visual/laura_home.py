"""Laura's home: one fictional Canadian family house every lifestyle photograph is taken in.

Owner requirement (P0 directive 2026-10-30, §14 "Laura's Home"): lifestyle images should look
like authentic photographs inside Laura's fictional home -- natural, comfortable, realistic,
lived-in, consistent across photographs and appropriate for a Canadian family; no artificial
luxury showroom; the nursery, kitchen and living areas must feel like parts of the same house;
ordinary household details, realistic lighting and natural composition; never a competitor's
home or photographs.

What existed before this module: the FLUX 3 scene took its environment from the reserved
outfit's free-text `setting`, and with none the prompt fell back to "a calm, natural setting
suited to the product" (`creative.flux_prompt`). Every generation therefore invented a new
room. That is the room drift the owner saw while generating images by hand.

So the house is code, in the same spirit as the canonical identity: a fixed set of rooms, each
with stable structural details (floor, walls, windows, light, anchor furniture) and a short
list of ordinary lived-in details, plus details shared by the whole house so adjacent rooms
read as one home. A product category is assigned one room (`ROOM_FOR_CATEGORY`), so every
lifestyle frame of a listing is in the same room by construction, and two products in the
same room are photographed in the same room. The environment text is deterministic:
the same room always produces the same words.

Boundaries. This is art direction for the scene only. It never describes Laura (her identity
is `visual.canonical`, untouched here), never describes the product (that is the certified
pattern's), and never states that anything was photographed: generated images stay labelled as
generated by the existing disclosure gates. No model call, no network, CA$0.
"""
from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass

HOME_ID = "laura-home-v1"


@dataclass(frozen=True)
class Room:
    key: str
    name: str
    structure: str        # floor, walls, windows: what never changes between photographs
    light: str            # where the light comes from, at what time of day
    anchors: str          # the furniture a viewer recognises the room by
    lived_in: tuple[str, ...]   # ordinary details; one is chosen per frame, deterministically

    def to_dict(self) -> dict:
        return {"key": self.key, "name": self.name, "structure": self.structure,
                "light": self.light, "anchors": self.anchors, "lived_in": list(self.lived_in)}


