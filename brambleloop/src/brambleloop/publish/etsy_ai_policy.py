_LEET = str.maketrans({"0": "o", "1": "i", "3": "e", "4": "a", "5": "s", "7": "t", "@": "a",
                       "$": "s", "!": "i", "|": "l"})
_JOINERS = r"[-‐‑‒–—_.·•*~+/\\]"


def _fold(text: str) -> str:
    t = unicodedata.normalize("NFKC", text or "").translate(_INVISIBLE)
    t = "".join(c for c in unicodedata.normalize("NFD", t) if not unicodedata.combining(c))
    return t.casefold().translate(_CONFUSABLE)


def _tokens_with_leet(t: str) -> str:
    # a digit inside a word of letters is a letter in disguise ("h4ndmade"); a number is not
    return re.sub(r"\S+", lambda m: m.group(0).translate(_LEET)
                  if re.search(r"[a-z]", m.group(0)) and re.search(r"[0-9@$!|]", m.group(0))
                  else m.group(0), t)


def _collapse_spaced(t: str, keep_pronoun: bool = False) -> str:
    """"h a n d m a d e" -> "handmade": three or more single letters in a row are one word.
    With `keep_pronoun`, a leading "i"/"a" stays its own word ("I d e s i g n e d")."""
    def join(m: re.Match) -> str:
        letters = m.group(0).split(" ")
        if keep_pronoun and letters[0] in ("i", "a") and len(letters) >= 4:
            return letters[0] + " " + "".join(letters[1:])
        return "".join(letters)
    return re.sub(r"\b(?:[a-z] ){2,}[a-z]\b", join, t)


def forms(text: str) -> tuple[str, ...]:
    """Normalised forms: joiners as spaces ("hand made") and joiners removed
    ("handmade", "designed" from "de-signed"). Both are scanned."""
    t = _tokens_with_leet(_fold(text))
    spaced = re.sub(_JOINERS, " ", t)
    joined = re.sub(rf"(?<=[a-z]){_JOINERS}+(?=[a-z])", "", t)
    out = []
    for f in (spaced, joined):
        f = re.sub(r"[^a-z0-9' ]+", " ", f)
        f = re.sub(r"'", " ", f)  # we've -> we ve, i'm -> i m (auxiliaries)
        f = re.sub(r"\s+", " ", f).strip()
        out.append(_collapse_spaced(f))
        out.append(_collapse_spaced(f, keep_pronoun=True))
    return tuple(dict.fromkeys(out))


