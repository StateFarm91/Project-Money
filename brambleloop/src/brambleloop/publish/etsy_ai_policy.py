"""Etsy's AI and authorship rules as a structural listing check (ENG-ETSY-AI-POLICY, w6).

Etsy Help Center, read through the public article API on 2026-11-19 (see
research/final_build/w6/etsy_ai_policy_audit.md for how each page was read):

* 44297885802647 (edited 2026-11-11): "Sellers must still disclose when an item is created
  using AI and cannot misrepresent AI-generated work as handmade or entirely their own
  creation."
* 115015663347 (edited 2026-11-06): "If you use AI to edit any of your listing photos, note
  whether images were edited in your listing description."

DESIGN (ENG-ETSY-AI-FIX, review H1). The first version was a regex blacklist of claims, and a
blacklist loses to the next synonym ("Our team designed this", "Lovingly handcrafted",
"Test-crocheted"). This is structural instead:

1. Every statement about who made, designed, wrote, tested or photographed the product comes
   from a CLOSED allowlist (`HONEST_STATEMENTS`): the company's own generated sentences, each
   true by construction (`platform_policy.DISCLOSURES`, `publish.pdf.AI_DISCLOSURE`,
   `publish.sample_photo.disclosure_copy`, whose truth `sample_photo.copy_problems` gates).
2. Those exact sentences are removed, and whatever free text remains is normalised (Unicode
   NFKC, case-fold, accents, zero-width and soft hyphens, look-alike letters, digits used as
   letters, s p a c e d and h.y-p_h.e.n.a.t.e.d words) and refused if it carries ANY
   authorship, making, testing or sample claim, in any inflection or UK spelling. It does not
   matter whether the free-text claim happens to be true: an honest statement has exactly one
   source, and it is the allowlist.

A refusal is a HOLD with a reason (`hold_card`), not a silent error string: a false positive
("download my pattern" was one) reaches the owner as a card naming the phrase and the rule.

The guard only adds refusals. It never satisfies or relaxes another gate, never claims human
authorship and never states an owner attestation (Etsy's `who_made` is the owner's, audit
owner exception B). `publication_status` is UNKNOWN until a named person records a reading of
Etsy's current AI rules for functional guides; UNKNOWN holds publication and nothing else.
"""
