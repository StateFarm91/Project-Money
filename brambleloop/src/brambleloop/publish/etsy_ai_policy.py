_COMPILED = tuple((label, re.compile(rx)) for label, rx in _RULES)


def _residue(text: str) -> str:
    out = text or ""
    for sentence in honest_statements():
        out = out.replace(sentence, " ")
    return out


def claims(text: str) -> list[tuple[str, str]]:
    """(rule, phrase) for every authorship/making/testing/sample claim in the free text that
    is left once the allowlisted honest sentences are removed."""
    found: dict[tuple[str, str], None] = {}
    # One sentence at a time: a window never spans "...made. Edited by hand..." (a real false
    # positive). Joiner dots ("h.a.n.d") are not followed by a space, so they do not split.
    sentences = [x for x in re.split(r"[.!?;:\n]+(?=\s|$)", _residue(text)) if x.strip()]
    for form in (f for sentence in sentences for f in forms(sentence)):
        for label, rx in _COMPILED:
            for m in rx.finditer(form):
                found[(label, m.group(0).strip())] = None
    return sorted(found)


def authorship_claim_problems(text: str) -> list[str]:
    """One refusal per claim in free listing copy (kept name: etsy.build_payload reads it)."""
    return [f"{CODE}: the listing copy makes a {label} claim ({phrase!r}). Statements about "
            f"who made, designed, tested or photographed a product come only from the closed "
            f"allowlist of honest sentences (publish.etsy_ai_policy.honest_statements); this "
            f"pattern is compiled from a validated specification with AI assistance (Etsy Help "
            f"44297885802647: sellers 'cannot misrepresent AI-generated work as handmade or "
            f"entirely their own creation')" for label, phrase in claims(text)]


def hold_card(db, *, artifact: str, problems: list[str], where: str = "listing") -> dict:
    """Raise (or restate) the owner hold card for refused listing copy. Returns the card.

    A refusal that may be a false positive must reach a person with its reason; an error
    string in a job log reaches nobody. The card holds publication of this copy only."""
    from ..ops import owner_queue

    problems = [str(p) for p in problems if p]
    if not problems:
        return {}
    key = f"authorship_copy_hold:{artifact}"
    reason = (f"Listing copy for {artifact} ({where}) was held by the authorship guard: "
              + " | ".join(p[:300] for p in problems[:5]))
    with db.session() as s:
        row = owner_queue.ensure(
            s, key, action=(f"Review the held listing copy for {artifact}: remove the "
                            f"authorship/making/testing claim, or report the phrase as a false "
                            f"positive so the guard can be narrowed"),
            reason=reason[:2000], max_cost_cad=0.0, minutes=5,
            consequence_of_delay="this listing's copy is not published until it is fixed",
            blocks=f"publication of {artifact}",
            why_software_cannot=("rewording copy that names who made a product is a "
                                 "representation; the guard refuses, it does not rewrite"))
        card = {"id": row.id, "requirement_key": key, "reason": row.reason,
                "blocks": row.blocks, "problems": problems}
        s.commit()
    return card


def publication_status(db) -> dict:
    """Whether Etsy's current AI rules permit this shop's AI-assisted functional guides.

    UNKNOWN until a named person records a reading (`READING_ACTION` audit row with
    `status` PERMITTED or PROHIBITED, `read_by` and `read_on` on or after `LATEST_EDIT`).
    The open question (audit section 1): a web-search summary claims an October 2026 Seller
    Handbook change bars AI-generated functional guides; the Handbook answers 403 to
    automation, so software cannot resolve it. UNKNOWN and PROHIBITED hold publication;
    internal work continues. An unreadable record is UNKNOWN, never PERMITTED."""
    hold = ("held: Etsy AI policy status {status} -- whether Etsy's current rules permit "
            "AI-assisted crochet patterns (functional guides) has not been read by a named "
            "person since the rules were edited {edit} (audit owner exception B); "
            "publication waits, internal work continues")
    try:
        from sqlalchemy import select

        from ..core.models import AuditLog

        with db.session() as s:
            rows = list(s.scalars(select(AuditLog).where(AuditLog.action == READING_ACTION)
                                  .order_by(AuditLog.id.desc()).limit(20)))
            readings = [dict(r.detail or {}) for r in rows]
    except Exception:  # noqa: BLE001 - unreadable is UNKNOWN
        readings = []
    for d in readings:
        status = str(d.get("status") or "").upper()
        read_by = str(d.get("read_by") or "").strip()
        try:
            read_on = date.fromisoformat(str(d.get("read_on") or "")[:10])
        except ValueError:
            continue
        if (status not in (PERMITTED, PROHIBITED) or not read_by
                or read_on < date.fromisoformat(LATEST_EDIT) or read_on > date.today()):
            continue
        if status == PERMITTED:
            return {"status": PERMITTED, "hold": False, "reason": "", "reading": d}
        return {"status": PROHIBITED, "hold": True, "reading": d,
                "reason": hold.format(status=PROHIBITED, edit=LATEST_EDIT)
                .replace("has not been read by a named person since",
                         f"was read by {read_by} on {read_on} as PROHIBITED since")}
    return {"status": UNKNOWN, "hold": True, "reading": None,
            "reason": hold.format(status=UNKNOWN, edit=LATEST_EDIT)}
