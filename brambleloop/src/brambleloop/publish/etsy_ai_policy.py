# Misspellings ("I desgined", "designd by me", "hanmade", "Handmaid"): a token one edit
# (insertion, deletion, substitution or adjacent swap) from one of these words is that word.
# Only long words: a one-edit neighbour of a short word is too often another real word.
_FUZZY_WORDS = ("design", "designed", "designer", "designing", "handmade", "handcrafted",
                "homemade", "created", "creator", "creation", "crafted", "artisan",
                "artisanal", "original", "conceived", "invented", "dreamed", "photographed",
                "photograph", "samples", "prototype", "verified", "handspun", "authored",
                "crocheted", "illustrated")
_FUZZY_BENIGN = frozenset({"designs", "creates", "crafts", "originals", "resign", "deign",
                           "crochets", "drafted", "treated", "crated"})


def _osa(a: str, b: str) -> int:
    """Optimal string alignment distance (Damerau-Levenshtein without repeated edits)."""
    if abs(len(a) - len(b)) > 1:
        return 2
    prev2, prev = None, list(range(len(b) + 1))
    for i in range(1, len(a) + 1):
        cur = [i] + [0] * len(b)
        for j in range(1, len(b) + 1):
            cost = a[i - 1] != b[j - 1]
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost)
            if (prev2 is not None and i > 1 and j > 1 and a[i - 1] == b[j - 2]
                    and a[i - 2] == b[j - 1]):
                cur[j] = min(cur[j], prev2[j - 2] + 1)
        prev2, prev = prev, cur
    return prev[-1]


def misspelt(form: str) -> list[str]:
    """Tokens of a normalised form that are a one-edit misspelling of an authorship word."""
    out = []
    for tok in form.split():
        if len(tok) < 6 or tok in _FUZZY_WORDS or tok in _FUZZY_BENIGN:
            continue
        if tok.startswith("handma") or any(_osa(tok, w) == 1 for w in _FUZZY_WORDS):
            out.append(tok)
    return out


def _residue(text: str) -> str:
    out = text or ""
    for sentence in honest_statements():
        out = out.replace(sentence, " ")
    return out


def claims(text: str) -> list[tuple[str, str]]:
    """(rule, phrase) for every authorship/making/testing/sample claim in the free text that
    is left once the allowlisted honest sentences are removed."""
    found: dict[tuple[str, str], None] = {}
    # One sentence at a time: a window never spans "...made. Edited by hand..." (a real false
    # positive). Joiner dots ("h.a.n.d") are not followed by a space, so they do not split.
    sentences = [x for x in re.split(r"[.!?;:\n]+(?=\s|$)", _residue(text)) if x.strip()]
    for form in (f for sentence in sentences for f in forms(sentence)):
        for label, rx in _COMPILED:
            for m in rx.finditer(form):
                found[(label, m.group(0).strip())] = None
        for tok in misspelt(form):
            found[("misspelt authorship or making", tok)] = None
    return sorted(found)


