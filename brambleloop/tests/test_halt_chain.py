"""eng/halt-chain: a targeted rebuild that starts at certification drives the whole chain.

Production (19h12, halt 380): eleven halted products each retried a rebuild whose earliest
outstanding class was `certificate`, so the rebuild enqueued `gate.certify`. Certification ran,
but the release hash was unchanged, so its `listing.draft` was enqueued under the original
chain's key, found that finished job, and nothing after certification ran again. The
evidence read `chain: ["gate.certify:done"]` with the marketing, SEO, pricing and PDF rows
still outstanding, and every verify pass re-opened `rebuild-incomplete`.

This runs the real chain through `Worker.run_once`: one product is built, its certificate
and a marketing row are made stale, a targeted rebuild is requested for both, and the test
proves the rebuild token reaches listing.draft and every later stage, that the marketing row
is regenerated by this attempt, and that the verify pass records it as completed.
"""
