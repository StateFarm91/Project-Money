def _drain(db, name, limit=600):
    # one product's chain (supply refill left pending, as in test_cert_rebuild_chain)
    chain_only = [t for t in handlers.known() if t != "supply.admit"]
    w = Worker(db, name, phase=Phase.SHADOW, lease_seconds=900, job_types=chain_only)
    for _ in range(limit):
        if not w.run_once():
            break


def _rows(db, slug, cls):
    with db.session() as s:
        return [(r.artefact_key, dict(r.inputs or {}), r.job_id) for r in s.scalars(
            select(ArtefactProvenance).where(ArtefactProvenance.product_slug == slug,
                                             ArtefactProvenance.artefact_class == cls))]


def _set_ref(db, cls, key, ref, value):
    with db.session() as s:
        row = s.scalar(select(ArtefactProvenance).where(
            ArtefactProvenance.artefact_class == cls, ArtefactProvenance.artefact_key == key))
        inputs = dict(row.inputs)
        old = inputs[ref]
        inputs[ref] = value
        row.inputs = inputs
        return old


_STATE: dict = {}


def test_a_rebuild_starting_at_certification_reruns_the_chain_and_verifies():
    db = Database(f"sqlite:///{_TMP}/chain.db")
    db.create_all()
    Registry(db).seed_defaults()
    cir = builder.for_slug("cloudline-baby-blanket")
    slug = cir.slug
    JobQueue(db).enqueue("validator", "cir.compile", {"cir": cir.to_dict()},
                         idempotency_key="hc-compile")
    _drain(db, "hc-build")
    certs = _rows(db, slug, "certificate")
    marketing = _rows(db, slug, "marketing_asset")
    assert certs and marketing, "the chain produced no certificate or marketing rows"
    ref = f"cir:{slug}"
    cert_key, mk_key = certs[0][0], marketing[0][0]
    assert ref in marketing[0][1], marketing[0][1]
    real = _set_ref(db, "marketing_asset", mk_key, ref, "0" * 16)
    if ref in certs[0][1]:
        _set_ref(db, "certificate", cert_key, ref, "0" * 16)
    with db.session() as s:
        drafts_before = [j.id for j in s.scalars(select(Job).where(
            Job.job_type == "listing.draft"))]
    nodes = [f"certificate:{cert_key}", f"marketing_asset:{mk_key}"]
    job = JobQueue(db).enqueue("listing", "chain.rebuild",
                               {"product_slug": slug, "artefacts": nodes,
                                "reason": "test: halt-chain", "retry": "2026-11-21",
                                "fingerprints": {ref: {"old": "0" * 16, "new": real}}},
                               priority=0, idempotency_key="hc-rebuild")
    Worker(db, "hc-rebuild", phase=Phase.SHADOW, job_types=["chain.rebuild"]).run_once()
    with db.session() as s:
        out = dict(s.get(Job, job.id).outputs or {})
    assert out.get("stage") == "gate.certify", out
    assert set(out["requested"]) == set(nodes), out
    with db.session() as s:
        stage = s.get(Job, out["stage_job"])
        assert stage.job_type == "gate.certify" and stage.inputs.get("rebuild"), stage.inputs
        token = stage.inputs["rebuild"]
        verify = s.scalar(select(Job).where(
            Job.job_type == "chain.rebuild",
            Job.idempotency_key == f"rebuild-verify:{slug}:{job.id}:1"))
        verify_id = verify.id
    _drain(db, "hc-chain")
    with db.session() as s:
        drafts = [j for j in s.scalars(select(Job).where(Job.job_type == "listing.draft"))
                  if j.id not in drafts_before]
        assert drafts, "certification of the rebuild enqueued no new listing.draft"
        assert drafts[-1].inputs.get("rebuild") == token, drafts[-1].inputs
        assert drafts[-1].status == JobStatus.DONE, drafts[-1].last_error
        later = {j.job_type for j in s.scalars(select(Job).where(
            Job.id > out["stage_job"])) if (j.inputs or {}).get("rebuild") == token}
    for st in ("listing.draft", "assets.build", "pricing.position", "listing.seo"):
        assert st in later, (st, sorted(later))
    regenerated = [r for r in _rows(db, slug, "marketing_asset") if r[0] == mk_key][0]
    assert regenerated[1][ref] == real, "the marketing row was not regenerated"
    assert regenerated[2] > out["stage_job"], "the row was not written by this attempt"
    with db.session() as s:
        s.get(Job, verify_id).run_after = utcnow()
    Worker(db, "hc-verify", phase=Phase.SHADOW, job_types=["chain.rebuild"]).run_once()
    with db.session() as s:
        v = s.get(Job, verify_id)
        assert v.status == JobStatus.DONE, v.last_error
        vout = dict(v.outputs or {})
        completed = [r.artifact for r in s.scalars(select(AuditLog).where(
            AuditLog.action == "chain.rebuild_completed"))]
    assert f"marketing_asset:{mk_key}" in vout["completed"], vout
    assert vout["outstanding"] == [], vout
    assert f"marketing_asset:{mk_key}" in completed
    _STATE.update(db=db, slug=slug, mk_node=f"marketing_asset:{mk_key}", ref=ref, real=real,
                  stage_job=out["stage_job"], requested_by=job.id)


def test_a_superseded_name_is_set_aside_not_outstanding_and_never_completed():
    """Production: 11 of winter-village-graphghan's 20 outstanding names read SUPERSEDED
    (built from a release the product moved past). No stage rewrites those, so counted as
    outstanding they failed every verify pass and rebuild-incomplete could never close."""
    if not _STATE:
        test_a_rebuild_starting_at_certification_reruns_the_chain_and_verifies()
    from brambleloop.ops import artefacts as provenance

    db, slug = _STATE["db"], _STATE["slug"]
    pdf_key = _rows(db, slug, "pdf")[0][0]
    old_node = f"pdf:{pdf_key}"
    real_check = provenance.check

    def check(s, **kw):
        out = []
        for v in real_check(s, **kw):
            if f"{v.artefact_class}:{v.artefact_key}" == old_node:
                v = provenance.Verdict(v.artefact_class, v.artefact_key, v.product_slug,
                                       provenance.SUPERSEDED, why="built from an older "
                                       "release, superseded by the newest (test)")
            out.append(v)
        return out

    provenance.check = check
    try:
        job = JobQueue(db).enqueue(
            "listing", "chain.rebuild",
            {"product_slug": slug, "artefacts": [_STATE["mk_node"], old_node],
             "reason": "test: superseded", "verify": 1,
             "fingerprints": {_STATE["ref"]: {"old": "0" * 16, "new": _STATE["real"]}},
             "stage_job": _STATE["stage_job"], "requested_by": _STATE["requested_by"]},
            priority=0, idempotency_key="hc-superseded")
        Worker(db, "hc-sup", phase=Phase.SHADOW, job_types=["chain.rebuild"]).run_once()
    finally:
        provenance.check = real_check
    with db.session() as s:
        j = s.get(Job, job.id)
        assert j.status == JobStatus.DONE, j.last_error
        out = dict(j.outputs or {})
        verified = [dict(r.detail or {}) for r in s.scalars(select(AuditLog).where(
            AuditLog.action == "chain.rebuild_verified", AuditLog.job_id == job.id))]
    assert out["outstanding"] == [], out
    assert out["superseded"] == [old_node], out
    assert old_node not in out["completed"] and _STATE["mk_node"] in out["completed"], out
    assert verified and old_node in verified[-1]["superseded"], verified
    with db.session() as s:
        assert not [r for r in s.scalars(select(AuditLog).where(
            AuditLog.action == "chain.rebuild_completed", AuditLog.artifact == old_node))], \
            "a superseded name was claimed as rebuilt"


